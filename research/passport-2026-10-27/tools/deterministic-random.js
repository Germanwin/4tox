/* deterministic-random.js — ПРЕДЗАГРУЗКА (node -r) для диагностического
 * прогона: заменяет Math.random линейным конгруэнтным генератором.
 *
 * Зачем: сервер выбирает сид партии случайно (game/server/server.js →
 * randomSeed), поэтому два прогона одного сценария получили бы разные
 * острова, а задание требует одинаковых сида, размера и населения. Код
 * сервера при этом НЕ меняется: файл game/server/server.js остаётся байт в
 * байт тем же, что в коммите, — меняется только окружение процесса.
 *
 * Генератор влияет на выбор сида и код лобби. Мир по сиду строит
 * mapgen2/js/worldgen.js со своим RNG — он от Math.random не зависит.
 *
 * Запуск (как это делает tools/run-scenario.js):
 *   PASSPORT_RNG=20261027 node -r tools/deterministic-random.js \
 *        game/server/server.js --port 8899 --no-upnp
 *
 * Без предзагрузки сервер работает как обычно: файл ни на что не влияет,
 * пока его не подключили.
 */
'use strict';

let s = (Number(process.env.PASSPORT_RNG) || 20261027) >>> 0;
Math.random = function () {
  // LCG Numerical Recipes: одна и та же последовательность на любой машине и
  // в любом прогоне.
  s = (Math.imul(s, 1664525) + 1013904223) >>> 0;
  return s / 4294967296;
};
