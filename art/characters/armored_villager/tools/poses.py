# ЧТО ЗДЕСЬ ИЗМЕНИЛОСЬ И ПОЧЕМУ. Первая версия этой анимации была СБОРОМ
# (наклониться, взять, положить в корзину) — так её и записал первый README:
# «жителю нечего делать руками». Заказчик (2026-10-14) дал ему дело: подошёл к
# дереву — рубит его топором. Значит поза обязана читаться УДАРОМ, а не
# наклоном: рука с топором идёт сверху вниз, а не тянется к земле.
#
# ГДЕ КАКОЙ УГОЛ. Топор лежит поперёк оси руки (person.build_axe: 90.0° к
# предплечью), поэтому угол ЧЕРЕНКА к вертикали равен сумме плеча и локтя
# (sh + el), а не задаётся отдельно:
#
#     sh+el =  40°  черенок вперёд-вверх, топор перед собой на высоте пояса;
#     sh+el =  86°  ЗАМАХ: топор поднят до подбородка, кромка вверх-вперёд;
#     sh+el =  40°  УДАР: рука вниз-вперёд, топор впереди, у самых корней.
#
# ПОЧЕМУ ЗАМАХ НЕ ЧЕРЕЗ ГОЛОВУ. Клетка атласа 112 x 132 (как у лесоруба), и над
# опорой в ней 106 px. Замер (tools/axe_probe.py) считает верх кадра в ХУДШЕМ из
# восьми поворотов — там топор уходит ОТ камеры и проецируется выше всего:
#
#     sh+el = 86°  ->  96.4 px   (запас 9 px на контур в 2 px) — взято;
#     sh+el = 90°  ->  98.5 px                                      — уже впритык;
#     sh+el = 96°  -> 100.5..104.1 px (рука над головой)            — обрез.
#
# Отсюда и замах «перед лицом»: он же и честнее для валки — лесоруб рубит у
# корней, а не размахивает топором над головой. Замах держится два кадра
# (0.250 и 0.375): на 12 к/с это пауза в 1/12 с перед ударом, и она читается.
#
# УДАР СТОИТ НА ФАЗЕ 0.50, и это не «середина цикла», а расчёт: от него до
# конца цикла ровно полцикла, поэтому восемь ударов ложатся РОВНО в 5.00 с
# (js/villager.js: CHOP_TIME — 5 секунд заказчика). Игра считает удар по этой же
# фазе (CHOP_HIT), так что кадр удара и событие в игре — одно число.
#
# КИСТЬ (hand_r) — НОЛЬ ВО ВСЕХ КАДРАХ. Кисть в модели — продолжение того же
# лофта, что предплечье (build_arm), поэтому поворот кисти увёл бы топор,
# оставив кулак на месте. Угол удара набирается плечом и локтем.
#
# СТОЙКА = СТОЙКА ПОКОЯ. Ноги ВМЕСТЕ и параллельно, колени прямые — ровно так,
# как житель стоит в `idle` (это те же четыре числа, что в POSE_REST: hip 0,
# knee 0, ankle 0, out 1.5). Задана ОДИН раз и НЕ МЕНЯЕТСЯ по кадрам.
#
# ПОЧЕМУ УГОЛ НОГИ НЕ В ТАБЛИЦЕ. Заказчик (2026-10-16): «в момент удара топором
# одна нога улетает назад, так быть не должно. Ноги должны стоять на месте,
# шевелиться должен только корпус и руки». До этой правки таблица WORK вела
# hip/knee/ankle/out по кадрам (на ударе «присед глубже»: hip_l 13 -> 16,
# knee_l 10 -> 15, hip_r -11 -> -13, knee_r 16 -> 22), и замер показывал, что
# подошва уезжает на 0.17 юнита = 13 px — это и читалось шагом.
#
# Теперь углов ног в таблице НЕТ ВООБЩЕ: work() накладывает эту стойку ПОСЛЕ
# интерполяции ключей. Так требование «ступни неподвижны» выполняется по
