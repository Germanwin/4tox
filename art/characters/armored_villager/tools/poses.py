# WALK — шаг на 8 кадров. Углы аналитические: цикл обязан быть замкнутым, а
# ключи пришлось бы сшивать вручную и на стыке всегда лезет рывок.
# ==========================================================================
# ЧИСЛА ШАГА подобраны замером, а не на глаз: tools/gait_probe.py считает по
# скелету положение ступни ОТНОСИТЕЛЬНО ТАЗА и печатает шаг, опору и клиренс.
#
# ЧЕГО ТРЕБУЕТ ЗАКАЗЧИК (2026-10-16): «ноги должны равномерно делать махи вперёд
# и назад на одинаковое расстояние» — то есть |назад| / вперёд = 1.00 (прибор
# gait_probe: SIDE_TOL_WALK = 1.05). Требование АНТИАНАТОМИЧНОЕ (у человека
# сгибание бедра больше разгибания) и взято сознательно: заказчик видит в
# асимметрии «центр тяжести не посередине, а где-то спереди».
#
# ПОЧЕМУ ОДНИМ F ЭТО НЕ РЕШАЕТСЯ. Ступня — не конец бедра: на неё работают ещё
# колено (сгиб на переносе уводит ступню НАЗАД, когда бедро уже идёт назад) и
# стопа. Тройка (F, D, фаза колена) решена ЧИСЛЕННО под три условия сразу:
# симметрия 1.00, пик колена на фазе ПЕРЕНОСА (там, где бедро идёт вперёд) и
# шаг опоры 0.286 юнита — ровно столько, чтобы при SPEED = 1.26 кл/с в
# js/villager.js ступня не ехала по земле (см. gait_probe, «скорость без
# проскальзывания»).
WALK_HIP_F = 17.72      # размах бедра вперёд-назад, град (было 14.0)
WALK_HIP_D = 8.78       # добавка sin^2: выравнивает размах вперёд с размахом назад
WALK_KNEE_ST = 6.0      # колено в опоре — чуть согнуто, не «солдатик»
WALK_KNEE_SW = 28.0     # сгиб колена на переносе, град (было 24: при новом шаге
                        # ступня волочилась — клиренс 1.54 px при пороге 1.6)
# ФАЗА ПИКА КОЛЕНА: 250° -> пик сгиба приходится на середину переноса (кадр 0
# сетки). Было 225° (пик 315°), и после выравнивания размахов такая фаза
# перестала годиться по ЗАМЕРУ: на 315° бедро уже идёт назад (производная
# A·cos + 2D·sin·cos = −0.55), а на 360° — уверенно вперёд (+14.4). Прибор
# gait_probe судит именно по этому: «пик сгиба там, где бедро идёт назад» =
# ступня отбрасывается за таз. Анатомически пик в середине переноса и вернее:
# колено складывается сильнее всего в середине переноса, а не на отрыве.
WALK_KNEE_PH = 250.0    # фаза начала переноса (пик сгиба — на +90°)
WALK_KNEE_PW = 2.0      # сглаживание горба: 1 — узкий, 2 — плавный
WALK_ARM = 15.0         # размах плеча; ОБЕ руки — одинаково


def _hip_walk(t, f=None, d=None):
    """Бедро качается ВПЕРЁД-НАЗАД относительно таза, размах выровнен замером.

    Асимметрия тут не косметика, а ИЗМЕРЯЕМАЯ величина: ступня — не конец
    бедра, её уводит ещё и колено, поэтому «синус + sin²» подбирается так,
    чтобы замер gait_probe дал |назад| / вперёд = 1.00 (порог 1.05). Числа
    (WALK_HIP_F, WALK_HIP_D) — решение, а не вкус: см. комментарий выше.

    `f`/`d` — размах и добавка; по умолчанию канонные WALK_*, поэтому шаг
    считается ровно как раньше (носить охапку — тот же шаг, только короче).
    """
    s = math.sin(t)
    return (WALK_HIP_F if f is None else f) * s + \
        (WALK_HIP_D if d is None else d) * s * s


def _knee_walk(t, st=None, sw=None, ph=None):
    """Колено: почти прямое в опоре, сгибается на ПЕРЕНОСЕ (фаза 250..90°).

    Пик сгиба — на середине переноса, между отрывом (270°) и выносом вперёд
    (45°): ступня поднимается и проходит под тазом СОГНУТОЙ, а не
    отбрасывается назад. В первой версии пик стоял на 218°, то есть ровно
    тогда, когда бедро шло назад, — отсюда и «ноги уходят назад».

    `ph` — фаза начала переноса, и она ЯВНАЯ, а не одолженная у ходьбы: у
    носки своя (CARRY_KNEE_PH = 225°), и это ЗАМОРОЗКА, а не украшение. Пока
    фаза бралась из WALK_*, правка шага молча переписывала кадры `carry`, а
    носку заказчик трогать запретил, и её приёмка (симметрия 1.26, клиренс
    2.2 px) держится ровно на прежних числах.

    Возведение в степень WALK_KNEE_PW убирает излом max(0, ·): сгиб нарастает
    и спадает плавно, а не скачком в один кадр.
    """
    p = WALK_KNEE_PH if ph is None else ph
    u = 0.5 * (1.0 + math.sin(t - math.radians(p)))
    return (WALK_KNEE_ST if st is None else st) + \
        (WALK_KNEE_SW if sw is None else sw) * (u ** WALK_KNEE_PW)


def walk(i, n=8, carry=False):
    """Шаг. carry=True — женская фигура: в левой руке корзина, полный размах
    руки её «уносит» (заказчик видел в этом драку с ведром)."""
    th = TAU * (i % n) / float(n)
    st, ct = math.sin(th), math.cos(th)
    # Ноги в противофазе и по ОДНОЙ кривой со сдвигом на полцикла: так шаг
    # зеркален по построению, и «одна нога шире другой» невозможно.
    hip_l, knee_l = _hip_walk(th), _knee_walk(th)
    hip_r, knee_r = _hip_walk(th + math.pi), _knee_walk(th + math.pi)
    p = dict(
        # bob — смещение таза вверх-вниз. На итоговую фигуру он НЕ влияет:
        # ground_lock сдвигает всё тело целиком и сокращает его до нуля.
        # Настоящий «боб» получается сам — из геометрии опорной ноги.
        bob=-0.010 - 0.008 * math.cos(2.0 * th),
        # КОРПУС НЕ НАКЛОНЁН ВПЕРЁД — требование заказчика (2026-10-16):
        # «во время ходьбы персонаж немного наклонён вперёд... кажется, что
        # центр тяжести не посередине, а где-то спереди». Здесь стояло 3.0
        # (постоянный наклон вперёд), и это ПРОВЕРЯЕТСЯ прибором: gait_probe
        # мерит угол линии «таз -> шея» и падает, если постоянная составляющая
        # не ноль (LEAN_TOL). Ноль — значит ноль, а не «почти ноль».
        lean=0.0,
        side=1.6 * st,
        twist=-4.0 * st,
        # Грудь качается ВДВОЕ ЧАЩЕ шага: корпус клюёт на каждом шаге, а не на
        # каждом цикле. Заодно это единственный способ сделать ходьбу честно
        # зеркальной: cos(th) не антисимметричен между половинами цикла, и
        # левая рука с правой качались на 0.7 px по-разному (замер в
        # tools/gait_probe.py), хотя формула у них одна.
        #
        # ПОСТОЯННОЙ СОСТАВЛЯЮЩЕЙ ЗДЕСЬ НЕТ: было 1.0 - 0.8·cos(2t), то есть
        # те же +1° наклона вперёд, что и lean. Замер по восьми кадрам:
        # сумма cos(2t) = 0, значит средний наклон корпуса — ровно ноль.
        chest=-0.8 * math.cos(2.0 * th),
        head_pitch=-1.5,
        head_turn=2.5 * st,
        hip_l=hip_l, knee_l=knee_l, ankle_l=8.0 * math.sin(th + 2.4), out_l=1.8,
        hip_r=hip_r, knee_r=knee_r,
        ankle_r=8.0 * math.sin(th + math.pi + 2.4), out_r=1.8,
        # ОБЕ руки качаются одинаково и в противофазе друг другу: правая рука
        # вперёд, когда вперёд идёт левая нога. Раньше левая качалась на 5°
        # против 15° у правой — это осталось от женской позы «несу корзину»,
        # а у мужчины в руках ничего нет, и качалась ровно одна рука.
        sh_l=-WALK_ARM * st, el_l=16.0 + 6.0 * max(0.0, -st),
        armout_l=10.0, foreout_l=-3.0,
        sh_r=WALK_ARM * st, el_r=16.0 + 6.0 * max(0.0, st),
        armout_r=10.0, foreout_r=-3.0,
        # подол отстаёт от шага: на переносе уезжает назад и в сторону
        skirt_dx=-0.012 * st, skirt_dy=-0.004 * ct,
    )
    if carry:
        p.update(sh_l=-5.0 * st, el_l=26.0 + 4.0 * st)
    return p


