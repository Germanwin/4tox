def work(i, n=8):
    p = _keys(WORK + [(1.0, WORK[0][1])], (i % n) / float(n))
    # НОГИ — ПОСЛЕ ИНТЕРПОЛЯЦИИ: в таблице их нет, поэтому и промежуточных
    # значений у них быть не может. feet_lock снимает с ног повороты корпуса
    # (person.skeleton): корпус рубит, ступни стоят.
    p.update(WORK_STANCE)
    p['feet_lock'] = True
    # кисть не участвует в ударе: топор посажен в систему кисти (person.build_axe)
    p['hand_r'] = 0.0
    p['hand_l'] = p.get('hand_l', 0.0)
    # подол рубахи отстаёт от корпуса: без этого он «прилипает» к коленям.
    # ВДВОЕ СЛАБЕЕ, ЧЕМ БЫЛО (2026-10-16): на ударе подол уезжал назад на
    # 0.030·20/16 = 0.0375 юнита = 2.9 px — и это ЕДИНСТВЕННОЕ, что в кадре
    # рубки двигалось назад в нижней половине фигуры (ноги стоят, замер 0.00 px).
    # Заказчик читает такой сдвиг как «низ уехал назад», поэтому подол отстаёт
    # ровно настолько, чтобы не липнуть: 1.5 px.
    p['skirt_dy'] = -0.015 * p['chest'] / 16.0
    p['skirt_dx'] = -0.010 * p['twist'] / 13.0
    return p


