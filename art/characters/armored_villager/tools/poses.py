"""poses.py — idle / walk / work. Позы одной модели, а не три модели.

Почему углами, а не отдельными мешами: топология не меняется, значит кадры
анимации не могут разъехаться по форме, а «боб» корпуса получается сам —
ground_lock в person.build сажает фигуру так, чтобы ОПОРНАЯ ступня стояла на
земле. Рисовать покачивание руками не нужно: оно следствие шага.

Три анимации — те же имена и то же число кадров, что у героя
(mapgen2/assets/hero/atlas.json): idle 6 x 8 к/с, walk 8 x 12 к/с, work 8 x 12.
Так новый персонаж встаёт в игру рядом с героем без правок кода.
"""
import math

TAU = 2.0 * math.pi


def _lerp(a, b, t):
    return a + (b - a) * t


def _keys(keys, t):
    """Куски: [(фаза, {углы}), ...] -> углы на фазе t (0..1), линейно."""
    keys = sorted(keys)
    for i in range(len(keys) - 1):
        t0, a = keys[i]
        t1, b = keys[i + 1]
        if t0 <= t <= t1:
            k = 0.0 if t1 == t0 else (t - t0) / (t1 - t0)
            out = dict(a)
            for name, v in b.items():
                out[name] = _lerp(a.get(name, v), v, k)
            for name in a:
                if name not in b:
                    out[name] = a[name]
            return out
    return dict(keys[-1][1])


# ==========================================================================
# IDLE — стоит и дышит. Четыре кадра из шести: два «вдоха» на цикл.
# ==========================================================================
IDLE = [
    (0.00, dict(bob=0.000, chest=0.0, head_pitch=0.0, sh_l=5.0, sh_r=5.0,
                el_l=14.0, el_r=14.0, lean=1.0)),
    (0.25, dict(bob=0.006, chest=1.6, head_pitch=-1.2, sh_l=6.5, sh_r=6.5,
                el_l=15.5, el_r=15.5, lean=0.4)),
    (0.50, dict(bob=0.001, chest=0.4, head_pitch=0.8, sh_l=5.2, sh_r=5.2,
                el_l=14.2, el_r=14.2, lean=1.2)),
    (0.75, dict(bob=0.005, chest=1.2, head_pitch=-0.6, sh_l=6.0, sh_r=6.0,
                el_l=15.0, el_r=15.0, lean=0.6)),
]


def idle(i, n=6):
    p = _keys(IDLE + [(1.0, IDLE[0][1])], (i % n) / float(n))
    # лёгкий поворот головы: «осматривается», но без суеты
    p['head_turn'] = 3.0 * math.sin(TAU * (i % n) / float(n))
    p['head_tilt'] = 1.0 * math.sin(TAU * (i % n) / float(n) + 1.0)
    return p


