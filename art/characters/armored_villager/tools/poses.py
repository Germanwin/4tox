# CARRY — несёт охапку брёвен в ДВУХ руках. ЦИКЛ, 8 кадров, 12 к/с.
# ==========================================================================
# Заказчик: срубил дерево — отнёс брёвна в лагерь. Движок зовёт эту анимацию
# по имени `carry` и, если её нет, берёт `walk` — то есть житель идёт с пустыми
# руками. Содержание задано заказчиком: руки заняты, размаха руками нет, вес
# читается (корпус назад, шаг короче, плечи подняты).
#
# ПОЧЕМУ ФАЗА КАДРА 0 — НЕ НОЛЬ, КАК У WALK. Игра ЗАМОРАЖИВАЕТ нулевой кадр
# `carry`, когда житель сдаёт брёвна в лагере (контракт с движком, а не вкус):
# значит в нулевом кадре он обязан СТОЯТЬ, а не висеть в переносе. У walk кадр 0
# приходится на прохождение (обе ступни рядом, но колено переносимой ноги
# согнуто на 23.5° — ступня в воздухе). Поэтому цикл сдвинут так, чтобы кадр 0
# попал на ДВУГОЛУЮ ОПОРУ: обе подошвы на земле одновременно. Фаза выбрана
# замером (tools/logs_probe.py --phase: перебор фаз, минимум max(z_л, z_п)),
# а не на глаз: 90° даёт ровно ту позу, где передняя нога уже встала.
CARRY_HIP_F = 9.0        # шаг короче обычного (walk: 14) — с ношей не разбежишься
CARRY_HIP_D = 6.0        # (walk: 9) та же асимметрия «вперёд больше, чем назад»
# Колени. В опоре согнуты сильнее, чем на пустой ходьбе (walk: 6): под весом
# человек идёт «на полусогнутых». Перенос — по замеру клиренса
# (tools/gait_probe.py): при сгибе 8+18 = 26° пустая ступня поднималась на
# 1.4 px, и прибор честно писал «ступня волочится» (порог 1.6 px). 14+28 = 42°
# даёт 2.7 px. Больше 42° не берём: колено выше пояса под ношей не читается.
CARRY_KNEE_ST = 10.0     # колено в опоре, град
CARRY_KNEE_SW = 28.0     # добавка на переносе, град
CARRY_KNEE_PH = 225.0    # фаза переноса, град: СВОЯ, не одолженная у ходьбы.
                         # Нужна затем, чтобы правка шага (WALK_KNEE_PH) не
                         # переписала кадры носки: у carry заморожены и картинка,
                         # и приёмка (симметрия 1.26, клиренс 2.2 px).
CARRY_ANKLE = 10.0       # качание стопы (walk: 8): пятка не цепляет землю
CARRY_ARM_SH = 16.0      # плечо вперёд: рука уходит под охапку, а не над ней
CARRY_ARM_EL = 54.0      # локоть: sh+el = 70° — предплечье вперёд-ВНИЗ,
                         # охапка ложится к поясу (при 90° она вставала на грудь
                         # и на повороте 180 закрывала голову — видно на 4x)
CARRY_ARM_OUT = 7.0      # локти разведены: охапка не прижата к рубахе
CARRY_LEAN = -3.5        # корпус НАЗАД (в skeleton плюс — вперёд)
CARRY_CHEST = -1.5       # и грудь тоже назад: вес тянет за руки
CARRY_SHRUG = 0.010      # плечи подняты, 0.010 юнита = 0.8 px (person.skeleton)
CARRY_PHASE = 90.0       # фаза нулевого кадра, град (см. выше)


def carry(i, n=8):
    """Шаг с охапкой: ноги идут, руки держат.

    Руки НЕ качаются: sh/el/armout у обеих сторон — константы, поэтому охапка
    (person.build_logs, крепится к предплечью) не гуляет по кадру. Двигает её
    только корпус, и двигает плавно: lean и chest заданы константой с малой
    периодической добавкой, а side/twist — синусы шага. Резких скачков между
    кадрами нет по построению: все функции периодические.
    """
    th = TAU * (i % n) / float(n) + math.radians(CARRY_PHASE)
    st, ct = math.sin(th), math.cos(th)
    hip_l = _hip_walk(th, CARRY_HIP_F, CARRY_HIP_D)
    hip_r = _hip_walk(th + math.pi, CARRY_HIP_F, CARRY_HIP_D)
    knee_l = _knee_walk(th, CARRY_KNEE_ST, CARRY_KNEE_SW, CARRY_KNEE_PH)
    knee_r = _knee_walk(th + math.pi, CARRY_KNEE_ST, CARRY_KNEE_SW, CARRY_KNEE_PH)
    return dict(
        bob=-0.012 - 0.007 * math.cos(2.0 * th),
        lean=CARRY_LEAN,
        # Боковая качка и поворот таза — вдвое слабее шага: с ношей человек
        # идёт «в рамке», а не вразвалку. Числа подобраны замером габарита
        # (logs_probe: охапка не должна вылезать за клетку 112 x 132).
        side=1.2 * st,
        twist=-2.5 * st,
        chest=CARRY_CHEST - 0.5 * math.cos(2.0 * th),
        head_pitch=-0.5,
        head_turn=1.5 * st,
        hip_l=hip_l, knee_l=knee_l,
        ankle_l=CARRY_ANKLE * math.sin(th + 2.4), out_l=2.2,
        hip_r=hip_r, knee_r=knee_r,
        ankle_r=CARRY_ANKLE * math.sin(th + math.pi + 2.4), out_r=2.2,
        # ОБЕ руки — одинаково и без размаха: охапка лежит на предплечьях.
        # Кисти — ноль: кисть в модели одно целое с предплечьем (build_arm), и
        # её поворот увёл бы охапку, оставив кулак на месте (та же грабля, что
        # у топора в рубке).
        sh_l=CARRY_ARM_SH, el_l=CARRY_ARM_EL, armout_l=CARRY_ARM_OUT,
        foreout_l=0.0, hand_l=0.0,
        sh_r=CARRY_ARM_SH, el_r=CARRY_ARM_EL, armout_r=CARRY_ARM_OUT,
        foreout_r=0.0, hand_r=0.0,
        shrug_l=CARRY_SHRUG, shrug_r=CARRY_SHRUG,
        # подол отстаёт от шага, но слабее: при коротком шаге он и так не липнет
        skirt_dx=-0.006 * st, skirt_dy=-0.003 * ct,
    )


