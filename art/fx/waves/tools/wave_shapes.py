"""Таблица форм гребней — без Blender, чтобы её читала и пост-обработка.

Длина и высота в юнитах модели (1 юнит = 1 клетка карты). Длинные валы — это
накат, он и задаёт море; короткие — пена на ряби, она заполняет промежутки.
Высоты малы: гребень это вода, поднявшаяся на четверть клетки, а не бугор.

Порядок важен: `js/waves.js` выбирает форму по номеру, и для валов вдоль
течения чаще берутся первые (длинные), а для фронтов поперёк — последние.
"""

SHAPES = (
    (4.20, 0.20, False),
    (3.00, 0.18, False),
    (2.10, 0.16, False),
    (1.40, 0.13, False),
    (0.95, 0.11, True),
)


def shape(i):
    return SHAPES[i % len(SHAPES)]
