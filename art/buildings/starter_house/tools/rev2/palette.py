"""palette.py — палитра РАТУШИ для стартового дома. Цвета заданы ЧИСЛАМИ.

Почему так, а не семействами атласа
-----------------------------------
Первая ревизия дома красилась 21 материалом (7 семейств x 3 тона, тон по
нормали фасета).  Заказчик: «крыша другого цвета, он вообще другого стиля».
Причина: у ратуши НЕТ тонов по нормали — у неё ДВЕНАДЦАТЬ фиксированных
материалов, и один и тот же цвет лежит на всей плоскости, как её ни поверни.

Поэтому здесь тот же список, что в `townhall/tools/townhall.py::palette()` —
те же ключи и те же hex.  Дом и ратуша обязаны быть из одной бочки краски:
любой свой оттенок сразу читается чужим.

    ОБМАЗКА (стены)      wall     #93714A
    СИЛОВОЙ КАРКАС       timber   #5E3D1E
    БАЛКИ, ОБВЯЗКА       beam     #8A6238
    ДОСКИ, СТАВНИ        plank    #A07C4C
    СОЛОМА               thatch   #A8823C
    СТАРАЯ СОЛОМА        thatch2  #8E6C2C
    ЦОКОЛЬ, БУЛЫЖНИК     stone    #8E9498
    ТЁМНЫЙ КАМЕНЬ        stone2   #6E747A
    МОХ                  moss     #466B34
    ПРОЁМЫ, НУТРО        dark     #1A140E
    УТОПТАННАЯ ЗЕМЛЯ     dirt     #7A6244
    ЖЕЛЕЗО               iron     #3A3A3E
"""
# Тот же список и те же значения, что у ратуши (townhall.py::palette()).
COLORS = (
    ('wall',    0x93714A),
    ('timber',  0x5E3D1E),
    ('beam',    0x8A6238),
    ('plank',   0xA07C4C),
    ('thatch',  0xA8823C),
    ('thatch2', 0x8E6C2C),
    ('stone',   0x8E9498),
    ('stone2',  0x6E747A),
    ('moss',    0x466B34),
    ('dark',    0x1A140E),
    ('dirt',    0x7A6244),
    ('iron',    0x3A3A3E),
)

NAMES = tuple(k for k, _ in COLORS)

# ЗАТЕМНЕНИЕ БАЗОВЫХ ЦВЕТОВ.  Материал и спрайт — разные вещи: сцена поднимает
# тон (солнце 2.05 + небо 0.42), поэтому базовый цвет обязан быть ТЕМНЕЕ
# целевого.  Множитель подобран замером кадра: стиль-гейт требует >=93 %
# пикселей в палитре атласа, и при 1.0 выходило 36 %.
# Пересчитывается так: изменить DARKEN, собрать в живом Blender, замерить
# `scripts/audit.py --mine out/sh_0.png`.
DARKEN = 1.0


def _darken(h, k):
    """Умножить sRGB-цвет на k (покомпонентно), не выводя за пределы."""
    out = 0
    for sh in (16, 8, 0):
        c = int(round(((h >> sh) & 255) * k))
        out = (out << 8) | max(6, min(250, c))
    return out


HEX = {k: _darken(v, DARKEN) for k, v in COLORS}
HEX_BASE = dict(COLORS)
# Камень и железо — шершавее и матовее дерева и соломы (как у ратуши).
ROUGH = {'stone': 0.92, 'stone2': 0.92, 'iron': 0.78}


def rgb(name):
    """Цвет материала в sRGB 0..1."""
    h = HEX[name]
    return ((h >> 16) & 255) / 255.0, ((h >> 8) & 255) / 255.0, (h & 255) / 255.0


def check(module_palette):
    """Сверка с палитрой ратуши: {ключ: hex}.  Пусто = совпало."""
    diffs = []
    for name, h in COLORS:
        theirs = module_palette.get(name)
        if theirs is None:
            diffs.append((name, hex(h), None))
        elif int(theirs) != int(h):
            diffs.append((name, hex(h), hex(int(theirs))))
    return diffs
