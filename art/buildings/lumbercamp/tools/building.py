# ЯРУС 3: ПОЛЕННИЦА — туда житель складывает дрова
# --------------------------------------------------------------------------
def build_woodpile(parts, rng):
    """Штабель поленьев торцами в +Y (на камеру).

    Поленья лежат НЕ в идеальной плоскости: у каждого своё y и своя дрожь.
    Ровный торец штабеля читался бы дощатой стенкой, а не дровами.
    """
    rows = ((7, 0.00, 1), (7, 0.115, -1), (5, 0.075, 1))
    z = 0.02
    for ri, (cnt, shift, sgn) in enumerate(rows):
        r = LOG_R * (1.0 - 0.03 * ri)
        zc = z + r
        step = ((PILE_X1 - PILE_X0) - 2 * r) / max(1, cnt - 1)
        for k in range(cnt):
            cx = PILE_X0 + r + k * step + shift * sgn
            if cx > PILE_X1 - r:
                continue
            y0 = PILE_YB + rng.uniform(-0.012, 0.012)
            y1 = PILE_YF + rng.uniform(-0.012, 0.012)
            # Сечение каждого полена повёрнуто СВОЁ: у одинаковых шестигранников
            # боковины параллельны, и у соседей по ряду они попадают в одну
            # плоскость — это ловится как z-fighting (доля 0.70).
            ph = math.pi / 6.0 + ri * 0.30 + rng.uniform(-0.03, 0.03)
            v, f = prism(ngon(cx, zc, r, 6, phase=ph), y0, y1, 1)
            F.part(parts, 'log_pile_%d_%d' % (ri, k), 'trunk', v, f,
                   jit=0.004, seed=400 + ri * 13 + k)
        z += 2.0 * r * 0.94


