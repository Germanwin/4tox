# ЯРУС 2: КРОВЛЯ — ОДНОСКАТНАЯ, ПЛАСТАМИ ТЁСА
# --------------------------------------------------------------------------
def build_roof(parts, rng):
    """Сплошная подстилающая плита + ряды тёса поверх неё.

    Плита обязательна и помечена `nocull`: доски не покрывают скат без щелей,
    и в любую щель снизу видно изнанку (тонкие красные линии на карте изнанок).
    Доски утоплены в плиту, а не лежат на ней впритык: стык «плоскость в
    плоскость» даёт совпадающие плоскости и z-fighting.
    """
    prof = [(ROOF_YB, z_under(ROOF_YB) + ROOF_BASE_T),
            (ROOF_YF, z_under(ROOF_YF) + ROOF_BASE_T),
            (ROOF_YF, z_under(ROOF_YF)), (ROOF_YB, z_under(ROOF_YB))]
    # Плита не доходит до самых кромок: там стоят лобовые доски, и если обе
    # детали кончаются одной плоскостью, получается пара «совпадающих
    # плоскостей» с долей 0.97 — то самое мерцание, которое ловит `coplanar`.
    v, f = F.prism_x(prof, ROOF_X0 + 0.010, ROOF_X1 - 0.010)
    F.part(parts, 'roof_base', 'leaf_autumn', v, f, jit=0.002, seed=300,
           nocull=True)

    rows, cols = 3, 3
    span = ROOF_YF - ROOF_YB                      # длина ската от карниза к коньку
    step = span / rows
    lap = step * 0.34                             # нахлёст ряда на нижний
    for r in range(rows):
        # Ряды ЗАХОДЯТ друг на друга, а не стыкуются: у стыка «торец в торец»
        # обе детали кончаются одной плоскостью, и в кадре она мерцает.
        d_lo = max(0.0, r * step - lap)
        d_hi = min(span, (r + 1) * step) - (0.010 if r == rows - 1 else 0.0)
        y_hi = ROOF_YF - d_hi                     # выше по скату — меньше y
        y_lo = ROOF_YF - d_lo
        # Низ доски утоплен в плиту при ЛЮБОМ ряде: top - 0.030 <= 0.035.
        # Если доска висит над плитой (было 0.011), снизу в щель видно изнанку.
        top = ROOF_BASE_T + 0.008 * (r + 1)
        bot = top - 0.030
        pr = [(y_lo, z_under(y_lo) + top), (y_hi, z_under(y_hi) + top),
              (y_hi, z_under(y_hi) + bot), (y_lo, z_under(y_lo) + bot)]
        seg = (BOARD_X1 - BOARD_X0) / cols
        off = (seg / 2.0 if (r % 2) else 0.0) + r * 0.006
        for k in range(cols):
            x0 = max(BOARD_X0, BOARD_X0 + seg * k + off) + 0.004
            x1 = min(BOARD_X0 + seg * (k + 1) + off, BOARD_X1) - 0.004
            if x1 - x0 < 0.30:
                continue
            v, f = F.prism_x(pr, x0, x1)
            F.part(parts, 'board_%d_%d' % (r, k), 'leaf_autumn', v, f,
                   jit=0.002, seed=310 + r * 7 + k)
    # лобовые доски по торцам ската — призма по тому же контуру: брусок нижним
    # углом вышел бы выше тёса, и снизу была бы видна изнанка.  Верх доски выше
    # самого толстого ряда тёса, поэтому торцы досок спрятаны под ней.
    for sx_ in (ROOF_X0 + 0.035, ROOF_X1 - 0.035):
        pr = [(ROOF_YB, z_under(ROOF_YB) - 0.05),
              (ROOF_YF, z_under(ROOF_YF) - 0.05),
              (ROOF_YF, z_under(ROOF_YF) + ROOF_BASE_T + 0.052),
              (ROOF_YB, z_under(ROOF_YB) + ROOF_BASE_T + 0.052)]
        v, f = F.prism_x(pr, sx_ - 0.035, sx_ + 0.035)
        F.part(parts, 'barge_%d' % int(round(sx_ * 100)), 'trunk', v, f,
               jit=0.002, seed=340 + int(round(sx_ * 100)) % 97)
    # карнизная доска по передней кромке: закрывает торец плиты и тёса
    v, f = F.bar((ROOF_X0 + 0.02, ROOF_YF - 0.015, z_under(ROOF_YF) + 0.02),
                 (ROOF_X1 - 0.02, ROOF_YF - 0.015, z_under(ROOF_YF) + 0.02),
                 0.05, 0.13, caps=(0, 1))
    F.part(parts, 'eave_board', 'trunk', v, f, jit=0.002, seed=360)


