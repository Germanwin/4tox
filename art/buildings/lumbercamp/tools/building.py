# ЯРУС 1: ОПОРНЫЕ КАМНИ И СТОЛБЫ
# --------------------------------------------------------------------------
def build_posts(parts, rng):
    """Четыре столба на камнях.  Камни — не украшение: они дают наземный
    контур из КАМНЯ, по которому упаковщик атласа меряет посадку основания
    (`ground`), и столб не гниёт в земле."""
    for i, sx_ in enumerate(POST_X):
        for j, sy_ in enumerate(POST_Y):
            tag = '%d_%d' % (int(round(sx_ * 100)), int(round(sy_ * 100)))
            # seed — из индексов, а НЕ из hash(tag): hash строк в Python
            # рандомизирован между процессами, и сборка перестала бы быть
            # детерминированной (дрожь менялась бы от запуска к запуску).
            seed = 7000 + i * 10 + j
            v, f = F.box(sx_, sy_, 0.0, FOOT_T, FOOT_T, FOOT_H,
                         rz=math.radians(rng.uniform(-4, 4)),
                         keep=('+x', '-x', '+y', '-y', '+z', '-z'))
            F.part(parts, 'foot_' + tag, 'stone', v, f, jit=0.007, seed=seed)
            z1 = Z_BACK if sy_ < 0 else Z_FRONT
            v, f = F.box(sx_, sy_, FOOT_H - 0.03, POST_T, POST_T,
                         z1 - FOOT_H + 0.03,
                         keep=('+x', '-x', '+y', '-y', '+z', '-z'))
            F.part(parts, 'post_' + tag, 'trunk', v, f, jit=0.004, seed=seed + 1)


def build_plates(parts):
    """Прогоны по верху столбов: на них ложится кровля.

    Брус кладётся НА столб (низ прогона = верх столба), а не «примерно туда»:
    иначе на стыке щель, и кровля висит в воздухе.

    `caps=(0, 1)` обязателен: брусок без торцов — ПОЛАЯ ТРУБА, и сквозь
    открытый конец видно изнанку (в отчёте `xray probe` это 2448 px на прогон).
    """
    for k, (sy_, z0) in enumerate(((POST_Y[0], Z_BACK), (POST_Y[1], Z_FRONT))):
        v, f = F.bar((ROOF_X0 + 0.06, sy_, z0 + PLATE_H / 2.0),
                     (ROOF_X1 - 0.06, sy_, z0 + PLATE_H / 2.0), 0.14, PLATE_H,
                     caps=(0, 1))
        # nocull: прогон виден ТОЛЬКО в щели под свесом (кровля наклонена, и у
        # задней кромки между ним и плитой остаётся клин).  Автоотсев считает
        # верхнюю грань закрытой и снимает её — и в щели светит изнанка того же
        # прогона (полоса 1133 px на сетке ракурсов).
        F.part(parts, 'plate_%d' % k, 'trunk', v, f, jit=0.003, seed=200 + k,
               nocull=True)


