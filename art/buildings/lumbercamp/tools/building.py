def build(variant=None):
    """Собрать лагерь.  Возвращает список деталей (dict name/family/verts/faces)."""
    rng = random.Random(17)
    parts = []
    build_posts(parts, rng)
    build_plates(parts)
    build_roof(parts, rng)
    build_woodpile(parts, rng)
    build_block_axe(parts, rng)
    build_sawhorses(parts, rng)
    build_stumps(parts, rng)
    build_logs(parts, rng)
    build_barrel(parts, rng)
    build_fence(parts, rng)
    F.ground(parts)
    F.autocull(parts)
    return parts


