"""building.py — ЛАГЕРЬ ЛЕСОРУБА для 4tox/mapgen2, пятно 3 x 3.

Собран по скиллу `4tox-building-forge`.  Это НЕ дом: у лагеря нет стен, щипца
и трубы.  Есть навес-склад на четырёх столбах (под ним поленница — туда житель
складывает дрова), колода с воткнутым топором (оттуда житель берёт топор) и
рабочий двор вокруг: козлы с бревном, пни, брёвна, кадка, частокол.

Поэтому диапазоны приёмки (`SPEC['canon']`) у лагеря СВОИ и обоснованы типом
постройки, а не подогнаны под ответ:
    * `h_b` 1.40..2.10 — навес ниже дома (2.6..3.0): это не жильё, а склад;
    * `wall_h` 0.90..1.60 — высота столба навеса (у дома 1.35 — высота стены);
    * `pitch` 12..24   — ОДНОСКАТНАЯ кровля: у двускатной канон 32..55, у
      односкатного навеса уклон намеренно малый, иначе навес читается сараем;
    * `roof_wall` 0.06..0.45 — кровля навеса тонкая и почти плоская;
    * `tris` 300..1500 — класс `building`, как у остальных построек.

Ярусы снизу вверх: опорные камни -> столбы -> прогоны -> кровля, и отдельно
двор, который ставится на землю.

Оси: X — ширина навеса, Y — его глубина, +Y — сторона, откуда смотрит камера
(азимут 45°).  Торцы поленьев и кромка топора направлены в +Y: именно эту
сторону видно в спрайте.
"""
import math
import random

import forge as F

# --------------------------------------------------------------------------
# КАНОННЫЕ РАЗМЕРЫ ЭТОЙ ПОСТРОЙКИ
# --------------------------------------------------------------------------
SPEC = dict(
    footprint=(3, 3),                 # клетки карты: лагерь занимает квадрат
    wall_x=1.90, wall_y=1.14,         # навес по осям столбов (X x Y)
    wall_h=None,                      # высота заднего столба: выводится ниже
    z_plinth=None,                    # верх опорных камней: выводится ниже
    z_wall=None,                      # верх столбов: выводится ниже
    pitch_deg=None,                   # уклон ската: выводится из TAN_P
    over_slope=0.18, over_end=0.12,   # свес по скату и по торцу, юниты
    ridge_z=None,                     # подставится из геометрии
    class_='building',
    canon=dict(h_b=(1.40, 2.10), wall_h=(0.90, 1.60), pitch=(12.0, 24.0),
               over_slope=(0.10, 0.30), over_end=(0.04, 0.14),
               roof_wall=(0.06, 0.45), min_detail=0.02, tris=(300, 1500)),
)

# --------------------------------------------------------------------------
# НАВЕС: геометрия, от которой считается всё остальное
# --------------------------------------------------------------------------
POST_X = (-1.30, 0.60)                # оси столбов по X (шаг 1.90)
POST_Y = (-1.30, -0.16)               # задний и передний ряды столбов
POST_T = 0.12                         # сечение столба
Z_BACK, Z_FRONT = 1.46, 1.02          # верх заднего и переднего столба
PLATE_H = 0.12                        # высота прогона
FOOT_H = 0.13                         # высота опорного камня
FOOT_T = 0.27

Z_PLATE_TOP_B = Z_BACK + PLATE_H      # 1.46 — низ кровли у заднего прогона
Z_PLATE_TOP_F = Z_FRONT + PLATE_H     # 1.10 — низ кровли у переднего прогона
TAN_P = (Z_PLATE_TOP_B - Z_PLATE_TOP_F) / (POST_Y[1] - POST_Y[0])
COS_P = math.cos(math.atan(TAN_P))

ROOF_T = 0.10                         # толщина кровли
ROOF_BASE_T = 0.035                   # подстилающая плита
ROOF_X0 = POST_X[0] - 0.12            # -1.42 кромка кровли по X
ROOF_X1 = POST_X[1] + 0.12            #  0.72
ROOF_YB = POST_Y[0] - 0.14            # -1.44 кромка у заднего ската
ROOF_YF = POST_Y[1] + 0.18            #  0.02 кромка у переднего (карниз)
BOARD_X0 = ROOF_X0 + 0.012            # тёс лежит между лобовыми досками и
BOARD_X1 = ROOF_X1 - 0.012            # заходит под них торцами


def z_under(y):
    """Низ кровли над координатой y: плоскость через верх обоих прогонов."""
    return Z_PLATE_TOP_F + (POST_Y[1] - y) * TAN_P


ROOF_TOP = z_under(ROOF_YB) + ROOF_T / COS_P
# Числа приёмки ВЫВОДЯТСЯ из геометрии, а не дублируются: подняли столб — и
# `wall_h` уехал бы, отчёт показывал бы старое число.  Это ровно та грабля,
# когда README и отчёт описывают то, чего в коде уже нет.
SPEC['ridge_z'] = round(ROOF_TOP, 3)
SPEC['pitch_deg'] = round(math.degrees(math.atan(TAN_P)), 2)
SPEC['z_plinth'] = FOOT_H
SPEC['z_wall'] = Z_BACK
SPEC['wall_h'] = round(Z_BACK - FOOT_H, 3)

# Двор: посадка наземных деталей.  Всё считается от центра пятна (0, 0).
PILE_X0, PILE_X1 = -1.12, 0.42        # поленница по X
PILE_YB, PILE_YF = -1.02, -0.30       # поленница по Y: отступ от линии столбов
LOG_R = 0.105                         # радиус полена
BLOCK = (0.80, 0.45)                  # колода с топором
BLOCK_R, BLOCK_H = 0.17, 0.46
HORSE = (-1.05, 0.45)                 # козлы: слева, вытянуты ВДОЛЬ Y
BARREL = (1.20, 0.95)                 # кадка


# --------------------------------------------------------------------------
# ПРИМИТИВЫ, КОТОРЫХ НЕТ В forge (призмы вдоль Y и Z)
# --------------------------------------------------------------------------
def prism(poly, a0, a1, axis):
    """Призма вдоль оси `axis` (0 = X, 1 = Y, 2 = Z) по контуру в двух других.

    `forge.prism_x` умеет только ось X, а поленнице нужны торцы в +Y, кадке и
    пням — круг в плане.  Контур задаётся в порядке возрастания номеров
    оставшихся осей: для X — (y, z), для Y — (x, z), для Z — (x, y).

    Обход выправляется знаком площади — как в `prism_x`.  Для оси Y одной
    выправки мало: перестановка (X, Z) нечётная, и нормали выходят внутрь,
    поэтому обход дополнительно инвертируется.  Это проверяет `canon.py`
    тестом «ребро дважды в одну сторону» и знаком объёма.
    """
    if a1 < a0:
        a0, a1 = a1, a0
    i, j = [k for k in range(3) if k != axis]
    p = list(poly)
    area = 0.5 * sum(p[k][0] * p[(k + 1) % len(p)][1]
                     - p[(k + 1) % len(p)][0] * p[k][1] for k in range(len(p)))
    if area < 0.0:
        p = p[::-1]
    n = len(p)

    def mk(a, uv):
        q = [0.0, 0.0, 0.0]
        q[axis], q[i], q[j] = a, uv[0], uv[1]
        return tuple(q)

    verts = [mk(a0, uv) for uv in p] + [mk(a1, uv) for uv in p]
    faces = [(k, (k + 1) % n, n + (k + 1) % n, n + k) for k in range(n)]
    faces.append(tuple(range(n - 1, -1, -1)))          # торец a0
    faces.append(tuple(range(n, 2 * n)))               # торец a1
    if axis == 1:
        faces = [tuple(reversed(f)) for f in faces]
    return verts, faces


def ngon(cx, cy, r, n, phase=0.0):
    """Правильный n-угольник в плане — сечение бревна, пня, кадки."""
    return [(cx + r * math.cos(phase + 2 * math.pi * k / n),
             cy + r * math.sin(phase + 2 * math.pi * k / n)) for k in range(n)]


def rot_x(verts, pivot, deg):
    """Поворот вокруг оси X через `pivot`.  Нужен, чтобы воткнуть топор."""
    c, s = math.cos(math.radians(deg)), math.sin(math.radians(deg))
    px, py, pz = pivot
    return [(v[0], py + (v[1] - py) * c - (v[2] - pz) * s,
             pz + (v[1] - py) * s + (v[2] - pz) * c) for v in verts]


def move(verts, dx, dy, dz=0.0):
    return [(v[0] + dx, v[1] + dy, v[2] + dz) for v in verts]


def taper_edge(verts, y_butt, y_edge, k):
    """Сузить голову топора к КРОМКЕ: у обуха полная толщина, у кромки доля `k`.

    Знак Y здесь важен: обух и кромка лежат по разные стороны головы, и
    сужение по |y| (как в первой версии) стачивало ОБА конца — голова
    превращалась в линзу.  Сборка идёт обычной призмой (нормали уже верны),
    а сужение — положительное масштабирование по X, ориентацию оно не меняет.
    """
    span = (y_edge - y_butt) or 1.0
    out = []
    for v in verts:
        t = min(1.0, max(0.0, (v[1] - y_butt) / span))
        out.append((v[0] * (1.0 + (k - 1.0) * t), v[1], v[2]))
    return out


