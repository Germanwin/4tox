"""village.py — ПАЛИТРА ДЕРЕВНИ: лагерь красится краской ратуши.

Задача заказчика (2026-10-15): «сделай так, чтобы 3D-модель лагеря лесоруба
была в цветовой гамме ратуши, а то он как будто из другого дерева сделан;
в той же палитре пускай будет».

Почему это отдельный файл, а не строчка в `building.py`.

До сих пор лагерь, как и дом жителя, красился СЕМЕЙСТВАМИ АТЛАСА ПРИРОДЫ
(`mapgen2/assets/sprites/atlas.png`): ствол `trunk` (#523521 / #4E321F /
#321E11) и осенняя листва `leaf_autumn` (#A8701F / #895B18 / #56360B).  Это
палитра ДЕРЕВЬЕВ И КАМНЕЙ, и на постройке она читается именно так: кровля
навеса красилась цветом осенней кроны (насыщенная охра), а столбы, поленница
и пни — цветом коры (тёмный шоколад).  Ратуша же с самого начала красится
СВОЕЙ краской — 12 материалов, снятых с эталона при её сборке
(`art/buildings/townhall/tools/townhall.py::palette()`): приглушённый
серо-коричневый каркас, светлые доски, песочная солома, светлый камень.
Отсюда и «сделан из другого дерева».

Что здесь лежит:

    ZONES    — зона -> краска.  Цвета и параметры материала (rough/spec)
               взяты у ратуши ДОСЛОВНО, вместе с её соглашением о цвете:
               `thpipe.make_material` и `blender_live.make_material` кладут
               hex ПРЯМО в `Base Color`, то есть трактуют его как ЛИНЕЙНЫЙ,
               а не как sRGB.  Это не ошибка и не повод «поправить»: обе
               стройки смотрят одной камерой, под одним солнцем и одним
               небом, и одна и та же краска обязана дать один и тот же
               пиксель.  Поэтому здесь лежат ТЕ ЖЕ числа — тогда совпадение
               доказывается тождеством материала, а не подгонкой.
    preview_rgb — цвет для софт-рендера `xray.py shot` (без Blender).  Это
               ПРЕДПРОСМОТР, а не палитра: гейт и приёмка им не меряются.

Чего здесь НЕЛЬЗЯ делать: подбирать цвет «на глаз» под ратушу.  Любой цвет,
которого нет у ратуши, — это новый цвет в игре, и появляться он должен
сначала в её палитре, а не в лагере.
"""

# Свет — тот же, что у всей игры (`canon.SUN_DIR`, `thpipe.SUN_DIR`).  Здесь он
# продублирован НАРОЧНО: `village.py` обязан читаться внутри Blender, а импорт
# `canon` тянет за собой `xray` и numpy, которых сборке формы не нужно.
import math

SUN_DIR = (-0.36, 0.30, 0.88)

# --------------------------------------------------------------------------
# КРАСКА РАТУШИ, ДОСЛОВНО
# --------------------------------------------------------------------------
# Источник: art/buildings/townhall/tools/townhall.py, функция palette().
# Формат: зона -> (линейный hex, roughness, specular, что это у ратуши).
TOWNHALL_PAINT = {
    'wall':    (0x93714A, 0.75, 0.12, 'обмазанный плетень'),
    'timber':  (0x5E3D1E, 0.75, 0.12, 'силовой каркас'),
    'beam':    (0x8A6238, 0.75, 0.12, 'балки, обвязка'),
    'plank':   (0xA07C4C, 0.75, 0.12, 'доски, ставни'),
    'thatch':  (0xA8823C, 0.75, 0.12, 'солома'),
    'thatch2': (0x8E6C2C, 0.75, 0.12, 'старая солома, заплаты'),
    'stone':   (0x8E9498, 0.75, 0.12, 'цоколь, булыжник'),
    'stone2':  (0x6E747A, 0.75, 0.12, 'тёмный камень'),
    'moss':    (0x466B34, 0.75, 0.12, 'мох на цоколе'),
    'dark':    (0x1A140E, 0.75, 0.12, 'проёмы, нутро'),
    'dirt':    (0x7A6244, 0.75, 0.12, 'утоптанная земля'),
    'iron':    (0x3A3A3E, 0.75, 0.12, 'колокол, обручи'),
}

# Какую краску ратуши берёт каждая зона лагеря.  Ключ — зона лагеря, значение —
# имя краски у ратуши.  Отдельная таблица, а не одно и то же имя, нужна там,
# где у лагеря вещь своя: навес у ратуши не соломенный, но кровля навеса
# ДОЛЖНА читаться той же кровлей, что у ратуши, иначе «другое дерево»
# возвращается через крышу.
ZONES = {
    # каркас, стойки, древки, обвязка — тёмное дерево ратуши
    'timber':  'timber',
    # пилёное дерево: ящик, древки, рукояти
    'plank':   'plank',
    # балки, обручи кадки, перекладины
    'beam':    'beam',
    # кровля/солома и полотнища знамени
    'thatch':  'thatch',
    'thatch2': 'thatch2',
    # камень: очаг, основание знамени, валуны по краю площадки
    'stone':   'stone',
    'stone2':  'stone2',
    # мох и трава на площадке
    'moss':    'moss',
    # утоптанная земля площадки
    'dirt':    'dirt',
    # проёмы, нутро, обмотки, зола
    'dark':    'dark',
    # железо: наконечники, котёл, обручи, бляха щита
    'iron':    'iron',
    # обмазанная стена — светлая кожа барабана
    'wall':    'wall',
}

# У лагеря нет кровли навеса: все 12 красок ратуши уже расписаны выше.
ROOF_AS_THATCH = False


def paint(zone):
    """Зона лагеря -> (линейный hex, rough, spec) краски ратуши."""
    src = ZONES[zone]
    hex_lin, rough, spec, _ = TOWNHALL_PAINT[src]
    return hex_lin, rough, spec


def paint_name(zone):
    return ZONES[zone]


# --------------------------------------------------------------------------
# ЗОНА ДЛЯ СОФТ-РЕНДЕРА
# --------------------------------------------------------------------------
# --------------------------------------------------------------------------
# ПРЕДПРОСМОТР (только софт-рендер `xray.py shot`)
# --------------------------------------------------------------------------
# Ратуша красится ОДНИМ материалом на деталь, и её фасеты различаются
# ЕСТЕСТВЕННЫМ затенением, а не выбором тона.  Лагерь теперь красится так же,
# поэтому у `xray.flat_rgb` (он выбирал тон из палитры атласа по нормали)
# спрашивать нечего — считаем затенение сами, линейно:
#
#     out_lin = base_lin * (SUN_K * max(0, n·sun) + SKY_K)
#
# Коэффициенты сняты пробой в живом Blender (`tools/village_probe.py`) и
# подставлены в PROBE ниже.  Это ПРЕДПРОСМОТР без Blender: он нужен, чтобы
# посмотреть силуэт и изнанки, а не чтобы утверждать цвет.  Цвет утверждает
# рендер и гейт.
# Снято линейной подгонкой по пробе (`tools/village_probe.py`,
# `tools/village_palette.json` -> `probe_table`): остаток модели <=0.078
# в линейном пространстве.  Небо подсинивает тень, поэтому у синего канала
# свой коэффициент.
SUN_K = 0.677
SKY_K = (0.257, 0.268, 0.296)


def _srgb(c):
    c = max(0.0, min(1.0, c))
    return c * 12.92 if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055


def _lin(c):
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def preview_rgb(zone, normal):
    """(r, g, b) 0..1 для софт-рендера: та же формула, что у фасета в кадре."""
    hex_lin, _, _ = paint(zone)
    base = [((hex_lin >> s) & 255) / 255.0 for s in (16, 8, 0)]
    d = math.sqrt(sum(c * c for c in SUN_DIR)) or 1.0
    b = max(0.0, sum(normal[i] * SUN_DIR[i] / d for i in range(3)))
    return [_srgb(base[i] * (SUN_K * b + SKY_K[i])) for i in range(3)]


def check():
    """Все ли зоны лагеря есть у ратуши, и все ли краски ратуши на месте."""
    bad = []
    for zone, src in ZONES.items():
        if src not in TOWNHALL_PAINT:
            bad.append('%s -> %s: у ратуши такой краски нет' % (zone, src))
    unused = sorted(set(TOWNHALL_PAINT) - set(ZONES.values()))
    if unused:
        # Не ошибка: у ратуши есть зоны, которых в лагере нет (мох, земля,
        # обмазка).  Но список печатается — чтобы «в палитре ратуши» не
        # превратилось в «в той части палитры, которую вспомнили».
        bad.append('краски ратуши, не взятые лагерем: %s' % ', '.join(unused))
    return bad


if __name__ == '__main__':
    for z in sorted(ZONES):
        h, r, s = paint(z)
        print('%-8s -> %-8s #%06X  rough %.2f spec %.2f  (%s)'
              % (z, paint_name(z), h, r, s, TOWNHALL_PAINT[ZONES[z]][3]))
    print('замечаний: %s' % (check() or 'нет'))
