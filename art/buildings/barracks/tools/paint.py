"""paint.py — КРАСКА ДЕРЕВНИ: казарма красится краской ратуши, все 12 цветов.

Задача заказчика по казарме: «та же школа, что у трёх построек в игре».  Школа
начинается с краски, и краска у деревни одна — 12 материалов, снятых с
эталона при сборке ратуши (`art/buildings/townhall/tools/townhall.py::palette()`,
машинная копия — `tools/thpal.py`).  Казарма не вводит ни одного нового
оттенка: её детали раскладываются по ТЕМ ЖЕ зонам, что у ратуши.

Как и у ратуши, зона — это МАТЕРИАЛ, а не тон: затенение даёт сцена (солнце
`(-0.36, 0.30, 0.88)`, энергия 2.05, небо `0.62, 0.66, 0.72`), и один и тот же
hex в `Base Color` обязан дать один и тот же пиксель у обеих построек.
Поэтому `paint()` отдаёт ровно те числа, что `thpipe.make_material` у ратуши:
hex трактуется как ЛИНЕЙНЫЙ, rough 0.75, spec 0.12 (разбор — в
`lumbercamp/tools/village.py`, там же история вопроса «другое дерево»).

Чего здесь НЕЛЬЗЯ делать: подбирать цвет «на глаз» под ратушу.  Любой цвет,
которого нет у ратуши, — это новый цвет в игре.
"""
import math

# Свет — тот же, что у всей игры.  Продублирован нарочно: `paint.py` обязан
# читаться внутри Blender, а импорт `canon` тянет numpy и Pillow.
SUN_DIR = (-0.36, 0.30, 0.88)

# --------------------------------------------------------------------------
# 12 красок ратуши, дословно (townhall/tools/thpal.py)
# --------------------------------------------------------------------------
# зона -> (линейный hex, roughness, specular, что это у ратуши)
TOWNHALL_PAINT = {
    'wall':    (0x93714A, 0.75, 0.12, 'обмазанный плетень'),
    'timber':  (0x5E3D1E, 0.75, 0.12, 'силовой каркас'),
    'beam':    (0x8A6238, 0.75, 0.12, 'балки, обвязка'),
    'plank':   (0xA07C4C, 0.75, 0.12, 'доски, ставни'),
    'thatch':  (0xA8823C, 0.75, 0.12, 'солома'),
    'thatch2': (0x8E6C2C, 0.75, 0.12, 'старая солома, заплаты'),
    'stone':   (0x8E9498, 0.75, 0.12, 'цоколь, булыжник'),
    'stone2':  (0x6E747A, 0.75, 0.12, 'тёмный камень'),
    'moss':    (0x466B34, 0.75, 0.12, 'мох на цоколе'),
    'dark':    (0x1A140E, 0.75, 0.12, 'проёмы, нутро'),
    'dirt':    (0x7A6244, 0.75, 0.12, 'утоптанная земля'),
    'iron':    (0x3A3A3E, 0.75, 0.12, 'колокол, обручи'),
}

# Зона казармы -> краска ратуши.  Здесь имена совпадают один в один: казарма
# берёт все 12 зон ратуши и не придумывает своих.  Таблица оставлена явной,
# чтобы `check()` могла сказать, какая краска ратуши не взята.
ZONES = {k: k for k in TOWNHALL_PAINT}


def paint(zone):
    """Зона -> (линейный hex, rough, spec) краски ратуши."""
    hex_lin, rough, spec, _ = TOWNHALL_PAINT[ZONES[zone]]
    return hex_lin, rough, spec


def paint_name(zone):
    return ZONES[zone]


# --------------------------------------------------------------------------
# ПРЕДПРОСМОТР (только софт-рендер `xray.py shot`)
# --------------------------------------------------------------------------
# Казарма красится одним материалом на зону, поэтому `xray.flat_rgb` не может
# взять тон из палитры атласа по нормали: считаем затенение линейно,
#
#     out_lin = base_lin * (SUN_K * max(0, n·sun) + SKY_K)
#
# Коэффициенты сняты пробой ратуши в живом Blender
# (`lumbercamp/tools/village_probe.py`, остаток модели <= 0.078 линейного).
# Это ПРЕДПРОСМОТР без Blender: он нужен, чтобы посмотреть силуэт и изнанки,
# а не чтобы утверждать цвет.  Цвет утверждают рендер и гейт.
SUN_K = 0.677
SKY_K = (0.257, 0.268, 0.296)


def _srgb(c):
    c = max(0.0, min(1.0, c))
    return c * 12.92 if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055


def preview_rgb(zone, normal):
    """(r, g, b) 0..1 для софт-рендера: та же формула, что у фасета в кадре."""
    hex_lin, _, _ = paint(zone)
    base = [((hex_lin >> s) & 255) / 255.0 for s in (16, 8, 0)]
    d = math.sqrt(sum(c * c for c in SUN_DIR)) or 1.0
    b = max(0.0, sum(normal[i] * SUN_DIR[i] / d for i in range(3)))
    return [_srgb(base[i] * (SUN_K * b + SKY_K[i])) for i in range(3)]


def check():
    """Все ли зоны казармы есть у ратуши и все ли краски ратуши взяты."""
    bad = []
    for zone, src in ZONES.items():
        if src not in TOWNHALL_PAINT:
            bad.append('%s -> %s: у ратуши такой краски нет' % (zone, src))
    unused = sorted(set(TOWNHALL_PAINT) - set(ZONES.values()))
    if unused:
        bad.append('краски ратуши, не взятые казармой: %s' % ', '.join(unused))
    return bad


if __name__ == '__main__':
    for z in sorted(ZONES):
        h, r, s = paint(z)
        print('%-8s -> %-8s #%06X  rough %.2f spec %.2f  (%s)'
              % (z, paint_name(z), h, r, s, TOWNHALL_PAINT[ZONES[z]][3]))
    print('замечаний: %s' % (check() or 'нет'))
