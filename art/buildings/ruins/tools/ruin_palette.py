"""ruin_palette.py — ПАЛИТРА РУИН: краски деревни + уголь и пепел.

Задача заказчика (2026-10-23, п.11): «цветом показать запустение/пожар:
обугленные тёмные участки, пепел, приглушённые краски; палитра — из
существующих материалов + тёмные угольные оттенки, без новых ярких цветов».

Отсюда правило файла:

    * двенадцать красок ратуши берутся ДОСЛОВНО из `village.py` (а тот — из
      `townhall/tools/townhall.py::palette()`), вместе с rough/spec.  Ни один
      существующий цвет не перекрашен: руина стоит рядом с целыми постройками
      и обязана быть из того же дерева и камня;
    * добавляются РОВНО ДВА новых цвета, и оба — тёмные, без яркости:
        `char` — обугленное дерево, почти чёрный с коричневым уходом;
        `ash`  — пепел, приглушённый серый.
      Они не «новые краски деревни»: это те же дерево и камень, обожжённые,
      и в осветлённом виде они остаются в тёмной части палитры.  Ярких
      (солома, мох, доска) среди них нет.
    * зона `soot` не заводится: сажа на стене — это `char`, а не отдельный
      цвет; лишний тон в атласе только размывает палитру.

ТОНА ДЛЯ СТИЛЬ-ГЕЙТА.  `audit.py --palette` читает готовые sRGB-тона, а не
базовые линейные hex.  Связь между ними — та же, что у `village_probe.py`:
фасет в кадре = `sRGB(base_lin * (SUN_K * c + SKY_K))`, где c — косинус к
солнцу (0.9 грань в небо, 0.6 на солнце, 0.3 в тень).  `tone_hex()` считает
это той же формулой `village.preview_rgb`, поэтому таблица тонов и кадр не
могут разойтись: `tools/palette_json.py` пишет `ruin_palette.json` ИЗ ЭТОГО
файла, а не наоборот.
"""
import math

import village as V

# --------------------------------------------------------------------------
# НОВЫЕ УГОЛЬНЫЕ КРАСКИ (единственное, чего нет у ратуши)
# --------------------------------------------------------------------------
# Линейный hex, как и все краски пайплайна (hex кладётся прямо в Base Color).
# Значения подобраны так, чтобы В КАДРЕ (после солнца и неба) они читались
# углём, а не чёрной дырой: char даёт ~#2E2A25, ash — ~#7A7770.
CHAR = 0x171009          # обугленное дерево
ASH = 0x2A2722           # пепел, зола

EXTRA_PAINT = {
    'char': (CHAR, 0.92, 0.02, 'обугленное дерево (новая тёмная краска)'),
    'ash': (ASH, 0.95, 0.02, 'пепел (новая тёмная краска)'),
}

# --------------------------------------------------------------------------
# ЗОНЫ РУИНЫ -> КРАСКА
# --------------------------------------------------------------------------
# Имена зон нарочно те же, что у целых построек (`village.TOWNHALL_PAINT`),
# плюс две угольные.  Здесь перечислены ВСЕ двенадцать красок ратуши, а не
# только те девять, что брал лагерь лесоруба: руина ратуши и казармы использует
# и обмазку (`wall`), и тёмный камень (`stone2`), и мох, и утоптанную землю.
# Генераторы руин берут зону по смыслу детали, а не цвет:
# `timber` — каркас, `beam` — обвязка, `plank` — доски, `thatch` — солома,
# `stone`/`stone2` — цоколь, `char` — то, что горело.
ZONES = {z: z for z in V.TOWNHALL_PAINT}
# Локальные имена зон, которых у ратуши нет как отдельных красок.
ZONES.update({'board': 'beam', 'board2': 'timber'})
ZONES.update({'char': 'char', 'ash': 'ash'})

PAINT = dict(V.TOWNHALL_PAINT)
PAINT.update(EXTRA_PAINT)


def paint(zone):
    """Зона руины -> (линейный hex, rough, spec) краски."""
    hex_lin, rough, spec, _ = PAINT[ZONES[zone]]
    return hex_lin, rough, spec


def paint_name(zone):
    return ZONES[zone]


def check():
    """Все ли зоны руины есть в палитре, и не завелось ли лишних красок."""
    bad = []
    for zone, src in ZONES.items():
        if src not in PAINT:
            bad.append('%s -> %s: такой краски нет' % (zone, src))
    return bad


# --------------------------------------------------------------------------
# ТОНА ДЛЯ СТИЛЬ-ГЕЙТА
# --------------------------------------------------------------------------
# Косинусы к солнцу, по которым `village_probe.py` снял тона целых построек.
TONE_C = (('light', 0.90), ('mid', 0.60), ('dark', 0.30))
# Нормаль с заданным косинусом к солнцу: берём её в плоскости солнца и
# вертикали, тогда `preview_rgb` даёт ровно ожидаемую яркость.
_SUN = V.SUN_DIR
_SUN_N = math.sqrt(sum(c * c for c in _SUN))


def _normal_for(c):
    """Единичная нормаль, у которой n·sun/|sun| == c."""
    # перпендикуляр к солнцу в плоскости XY (горизонтальная составляющая)
    hx, hy = _SUN[0] / _SUN_N, _SUN[1] / _SUN_N
    hn = math.hypot(hx, hy)
    if hn < 1e-9:
        return (0.0, 0.0, 1.0)
    px, py = -hy / hn, hx / hn
    sh = math.sqrt(max(0.0, 1.0 - c * c))
    return (hx * c + px * sh, hy * c + py * sh, _SUN[2] / _SUN_N * c)


def preview_rgb(zone, normal):
    """Та же формула, что `village.preview_rgb`, но по палитре руин.

    Своя копия нужна потому, что `village.preview_rgb` спрашивает краску у
    `village.paint`, а угля и пепла там нет.  Формула и коэффициенты — оттуда
    же (`SUN_K`, `SKY_K`), дословно: расходиться им негде.
    """
    hex_lin, _, _ = paint(zone)
    base = [((hex_lin >> s) & 255) / 255.0 for s in (16, 8, 0)]
    d = math.sqrt(sum(c * c for c in V.SUN_DIR)) or 1.0
    b = max(0.0, sum(normal[i] * V.SUN_DIR[i] / d for i in range(3)))
    return [V._srgb(base[i] * (V.SUN_K * b + V.SKY_K[i])) for i in range(3)]


def tone_hex(zone, c):
    r, g, b = preview_rgb(zone, _normal_for(c))
    return '#%02X%02X%02X' % (int(round(r * 255)), int(round(g * 255)),
                             int(round(b * 255)))


def tones(zone):
    return {key: tone_hex(zone, c) for key, c in TONE_C}


if __name__ == '__main__':
    print('замечаний: %s' % (check() or 'нет'))
    for z in sorted(ZONES):
        h, r, s = paint(z)
        print('%-8s -> %-8s #%06X  rough %.2f  %s'
              % (z, paint_name(z), h, r, tones(z)['mid']))
