def build_roof_remains(parts):
    """Кровля упала: большой пласт ПЕРЕД домом, малый — внутри, стропила.

    Первый прогон клал три широкие доски от стены к земле: в кадре они
    слились в гладкий настил-пандус, и руина читалась помостом.  Второй —
    прятал всю кровлю за стенами, и её не было видно.  Поэтому главный обвал
    лежит ПЕРЕД фасадом (одним краем на остатке стены, другим на полу двора),
    а внутри — только малая часть; стропила держатся на щипце.
    """
    # Малый пласт внутри: то, что провалилось в дом.
    quad = [(0.14, -1.20, ZD + 0.12), (0.72, -1.04, ZD + 0.18),
            (0.76, -0.24, ZD + 0.04), (0.22, -0.32, ZD + 0.06)]
    K.roof_panel(parts, 'roof_pile', quad, 0.08, fam='char', seed=401)
    # ОБВАЛ ПЕРЕД ДОМОМ — главный и самый крупный фасет кадра.
    quad = [(-0.70, 0.50, ZD + 0.38), (0.52, 0.56, ZD + 0.32),
            (0.62, 1.44, ZD + 0.02), (-0.60, 1.38, ZD + 0.02)]
    K.roof_panel(parts, 'roof_fallen_front', quad, 0.075, fam='thatch2',
                 seed=404)
    # обгоревшая кромка обвала — узкий брусок, не вторая панель
    K.beam(parts, 'roof_fallen_char', 'char', (-0.54, 1.34, ZD + 0.06),
           (0.60, 1.40, ZD + 0.06), 0.07, 0.06, seed=405, nocull=True)
    # Обрешётка под малым пластом.
    for k, y in enumerate((-0.86, -0.40)):
        K.beam(parts, 'roof_purlin_%d' % k, 'char',
               (0.70, y, 0.20 + ZD), (0.22, y, 0.10 + ZD), 0.05, 0.05,
               seed=420 + k, nocull=True)

    # Стропила: два держатся на щипце и уходят на пол, два лежат.
    for k, (x0, y0, z0, x1, y1) in enumerate((
            (-0.55, -1.10, 1.40, -0.10, -0.34),
            (-0.20, -1.12, 1.28, 0.28, -0.40))):
        K.beam(parts, 'rafter_%d' % k, 'char', (x0, y0, z0),
               (x1, y1, ZD + 0.02), 0.06, 0.07, seed=450 + k, nocull=True)
    K.fallen_beam(parts, 'rafter_ground_0', (-0.60, 0.34), (0.20, 0.72),
                  0.055, seed=452, fam='beam', z0=ZD)
    K.fallen_beam(parts, 'rafter_ground_1', (0.10, -1.14), (0.72, -0.72),
                  0.05, seed=453, fam='char', z0=ZD)

    # Конёк сорван: коньковое бревно лежит поперёк двора.
    K.fallen_beam(parts, 'ridge_fallen', (-0.34, -1.28), (-0.06, -0.50),
                  0.085, seed=460, fam='char', h=0.085, z0=ZD)


