import forge as F
import ruinkit as K

HERE = os.path.dirname(os.path.abspath(__file__))


def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod
    spec.loader.exec_module(mod)
    return mod


# Геометрия целого дома: константы и цоколь берутся ОТТУДА, а не переписаны.
HOUSE = _load('ruin_house_src',
              os.path.join(HERE, '..', '..', 'starter_house', 'tools', 'house.py'))

HX, HY = HOUSE.HX, HOUSE.HY                  # 0.83 x 1.40 — оси стен
WALL_T = 0.11                                # обломок толще обмазки: видно срез
Z0 = HOUSE.PLINTH_H                          # 0.15 — верх цоколя
# Пол внутри цоколя: у целого дома это верх плиты `plinth_top` — 0.15, а не
# ядро 0.13 (плита лежит на ядре и накрывает его).  Всё, что лежит ВНУТРИ
# пятна, лежит на плите: иначе обломок утоплен в цоколь и его не видно (первый
# прогон: половина двора «исчезла», а горелый пол ушёл под плиту).
ZD = 0.152
Z_RIDGE = HOUSE.Z_RIDGE_S                    # 2.60 — конёк целого дома (для сверки)

# Высоты остатков стен (верх куска, юниты от земли).  Числа — доли от
# Z0 + 1.0: руина ниже целой стены (1.42) примерно на треть.
H_FRONT = 0.78                               # +Y, к камере: сильнее всего
H_LEFT = 1.22                                # -X, к камере: выше всех
H_RIGHT = 0.88                               # +X
H_BACK = 1.02                                # -Y

SPEC = dict(
    footprint=(2, 3),
    wall_x=2.0 * HY,                         # вдоль конька (ось Y)
    wall_y=2.0 * HX,                         # поперёк скатов (ось X)
    wall_h=H_LEFT - Z0,                      # самый высокий остаток
    z_plinth=Z0,
    z_wall=H_LEFT,
    pitch_deg=None,                          # скатов нет: кровля упала
    over_slope=0.0,
    over_end=0.0,
    ridge_z=None,
    class_='ruin',
    # Канон КЛАССА РУИНЫ, а не дома: стены и высота намеренно ниже, потому что
    # это обломки.  Пятно, бюджет и минимальная деталь — как у построек.
    canon=dict(h_b=(1.55, 2.35), wall_h=(0.45, 1.25), tris=(300, 1500),
               min_detail=0.02),
)


