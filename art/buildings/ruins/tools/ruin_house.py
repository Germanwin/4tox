def build_small_debris(parts):
    for k, (cx, cy, w, ln, ang, fam) in enumerate((
            (0.05, 0.62, 0.16, 0.30, 22.0, 'thatch2'),
            (-0.48, 1.28, 0.14, 0.26, -14.0, 'thatch'),
            (0.72, 0.42, 0.12, 0.24, 60.0, 'thatch2'),
            (-0.20, -0.72, 0.13, 0.22, 8.0, 'thatch'))):
        K.shingle(parts, 'debris_shingle_%d' % k, cx, cy, w, ln, ang, 630 + k,
                  fam=fam, z=ZD + 0.01, thick=0.02, tilt=0.012)
    # угли и пепел
    K.char_pile(parts, 'char_pile_0', -0.05, 0.05, 0.20, 640, n=4, z0=ZD)
    K.char_pile(parts, 'char_pile_1', 0.48, 0.55, 0.15, 645, n=3, z0=ZD)
    K.ash_patch(parts, 'ash_hall', 0.05, -0.10, 0.42, 0.34, 650, z=ZD + 0.012)
    K.ash_patch(parts, 'ash_door', 0.0, 1.02, 0.30, 0.22, 651, z=ZD + 0.012)
    # выпавшие камни цоколя (лунка уже есть в цоколе)
    K.rubble(parts, 'rubble_left', -0.62, 0.90, 0.16, 660, fam='stone')
    K.rubble(parts, 'rubble_back', 0.55, -1.20, 0.14, 661, fam='stone2')
    # камни в лунку цоколя: целый дом вынул из ряда два валуна, руина
    # завалила лунку обломками — заодно закрыт срез грунта (иначе изнанка
    # plinth_trench 34 px).
    K.stone(parts, 'trench_stone_0', 'stone', 0.90, 0.74, 0.0, 0.09, 0.13,
            663, n=5)
    K.stone(parts, 'trench_stone_1', 'stone2', 0.90, 0.92, 0.0, 0.08, 0.10,
            664, n=5)
    K.stone(parts, 'stone_loose_top', 'stone2', 0.86, 0.20, 0.0, 0.10,
            0.12, 662, n=5)
    # вязанка соломы с фасада разлетелась: три пучка
    for k, (cx, cy, ang) in enumerate(((0.30, 1.30, 10.0),
                                        (0.54, 1.18, -22.0))):
        K.shingle(parts, 'straw_bundle_%d' % k, cx, cy, 0.12, 0.20, ang,
                  670 + k, fam='thatch', z=ZD + 0.01, thick=0.05, tilt=0.0)


# --------------------------------------------------------------------------
# СБОРКА
# --------------------------------------------------------------------------
def build(variant=None):
    parts = []
    build_base(parts)
    build_yard_burnt(parts)
    build_walls(parts)
    build_roof_remains(parts)
    build_small_debris(parts)
    K.finish(parts)
    return parts


