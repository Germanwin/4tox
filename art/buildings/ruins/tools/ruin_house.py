def build_walls(parts):
    """Четыре стены-обломка + каркас + щипец.

    Стена — цельная призма с рваной кромкой (`ruinkit.broken_wall`), толщиной
    0.16: обмазка целого дома 0.08 в руине не читается — срез должен быть
    виден.  Высоты: -X (к камере) самая высокая, +Y (фасад) самая низкая с
    проломом на дверь; щипец на -Y уцелел наполовину и держит силуэт дома.
    """
    # Стены стоят на плите цоколя, а не вровень с рядом валунов: наружная
    # плоскость уходит внутрь на 0.03.  Иначе боковина валуна и боковина
    # стены ложатся почти в одну плоскость (xray: пара, площадь 0.09).
    T = 0.14
    K.broken_wall(parts, 'wall_left', 'y', -HX + 0.02, -HY + 0.04, HY - 0.02, Z0, 1.18,
                  T, seed=211, holes=((0.30, 0.40),),
                  frac=(0.96, 0.78, 0.90, 0.62, 0.84, 0.70, 0.94))
    K.broken_wall(parts, 'wall_front', 'x', HY - 0.02, -HX + 0.04, HX - 0.02, Z0, 0.72,
                  T, seed=221, holes=((0.02, 0.66),),
                  frac=(0.92, 0.62, 0.80, 0.48, 0.68, 0.86))
    K.broken_wall(parts, 'wall_right', 'y', HX - 0.02, -HY + 0.02, HY - 0.04, Z0, 0.86,
                  T, seed=231, holes=((0.62, 0.40),),
                  frac=(0.84, 0.60, 0.74, 0.44, 0.68, 0.54))
    # ГЛАВНАЯ СТЕНА — задний щипец (-Y).  Целая руина дома узнаётся по
    # высокому щипцу: он один держит силуэт двускатной кровли, когда скатов
    # уже нет.  Кромка рваная, с проломом у правого края; верх 2.05, конёк
    # целого дома 2.60.
    prof = [(-HX, Z0), (-HX + 0.02, 1.52), (-0.52, 1.74), (-0.22, 2.04),
            (0.06, 1.62), (0.30, 1.78), (HX - 0.02, 1.24),
            (HX - 0.10, 0.94), (HX - 0.02, Z0)]
    v, f = F.prism(prof, -HY - 0.075, -HY + 0.075, axis=1)
    K.add(parts, 'gable_wall', 'wall', (v, f), jit=0.004, seed=241)
    K.beam(parts, 'gable_char', 'char', (-HX + 0.02, -HY - 0.01, 1.52),
           (-0.22, -HY - 0.01, 2.04), 0.075, 0.05, seed=242, nocull=True)
    # КАРКАС: стойки по углам и обвязка.  Без него стена читается забором;
    # брусок вынесен наружу на 0.02 и виден на просвет.
    K.broken_post(parts, 'post_left_front', -HX - 0.02, HY - 0.05, Z0, 0.86,
                  0.12, seed=270, lean=(0.01, -0.01), char=True)
    K.broken_post(parts, 'post_left_mid', -HX - 0.02, 0.30, Z0, 1.16,
                  0.12, seed=275, lean=(-0.02, 0.01))
    K.broken_post(parts, 'post_left_back', -HX - 0.02, -HY + 0.06, Z0, 1.10,
                  0.12, seed=271, lean=(-0.01, 0.01), char=True)
    K.broken_post(parts, 'post_right_back', HX + 0.02, -HY + 0.06, Z0, 0.62,
                  0.12, seed=272, char=True)
    # верхняя обвязка левой стены: один кусок на месте, второй сорван
    K.slab(parts, 'plate_left_a', 'beam', -HX - 0.045, -HX + 0.04,
           -HY + 0.06, -0.12, 1.02, 1.13, jit=0.003, seed=273)
    K.fallen_beam(parts, 'plate_left_b', (-0.94, 0.62), (-0.20, 0.94), 0.11,
                  seed=274, fam='char')
    # раскос фахверка в проломе: от стойки к обвязке
    K.beam(parts, 'brace_front', 'timber',
           (-HX + 0.04, HY - 0.08, Z0 + 0.14), (-0.32, HY - 0.08, 0.88),
           0.09, 0.08, seed=276)

    # Дверной проём: стойки снаружи, одна сорвана и лежит.
    K.slab(parts, 'door_jamb_l', 'timber', -0.40, -0.31, HY + 0.02, HY + 0.10,
           Z0, 0.98, jit=0.003, seed=280, nocull=True)
    K.slab(parts, 'door_jamb_r', 'timber', 0.31, 0.40, HY + 0.02, HY + 0.10,
           Z0, 0.78, jit=0.003, seed=281, nocull=True)
    K.beam(parts, 'door_lintel', 'char', (-0.44, HY + 0.05, 0.97),
           (0.44, HY + 0.05, 0.70), 0.10, 0.12, seed=282)
    K.slab(parts, 'door_leaf_fallen', 'plank', -0.28, 0.34, 0.58, 1.10,
           Z0 + 0.01, Z0 + 0.045, jit=0.004, seed=283)

    # ОКНО на левой стене: рама сорвана и висит на одном гвозде (наклонена).
    K.beam(parts, 'win_brace', 'char', (-HX + 0.01, -0.52, 0.78),
           (-HX + 0.01, -0.02, 0.58), 0.07, 0.07, seed=286)
    K.shingle(parts, 'win_frame_fallen', -0.62, 0.10, 0.28, 0.22, 62.0, 287,
              fam='plank', z=ZD + 0.01, thick=0.04, tilt=0.0)


