# ЦОКОЛЬ И ДВОР: те же места, что у целого дома
# --------------------------------------------------------------------------
def build_base(parts):
    """Цоколь целого дома — вызовом его же функции (лунка и мох на месте)."""
    HOUSE.build_plinth(parts)
    # Ядро цоколя закрыто сверху горелым полом, и автоотсев снимает его верх
    # (а снизу в него светит изнанка: 17 939 px).  Закрываем ядро и полку
    # целиком: 12 лишних трис дешевле дыры, которую видно на нижнем ракурсе.
    for p in parts:
        if p['name'] in ('plinth_core', 'plinth_top'):
            p['nocull'] = True


def build_yard_burnt(parts):
    """Двор стройки после пожара: брёвна и солома на тех же местах.

    Целый дом держит здесь штабель брёвен (x -0.99..-0.65, y -1.10..-0.50) и
    вязанку соломы (x ~0.68, y ~-1.20).  Они входят в наземный контур
    (`ground` = -0.918..0.993 по X карты), поэтому место сохранено: убрать их
    значило бы изменить `ground` целого дома, а он обязан совпасть.
    """
    rng = random.Random(51)
    # штабель: два нижних бревна целы, верхнее скатилось и обуглено
    for k, (cy, cz, fam) in enumerate(((-1.08, 0.055, 'char'),
                                       (-0.74, 0.055, 'beam'),
                                       (-0.50, 0.055, 'char'))):
        v, f = F.prism(F.ngon(cy, cz, 0.055, 6, phase=0.36 * k + 0.2),
                       -0.98, -0.66, axis=0)
        v = [(q[0], q[1], q[2] + ZD) for q in v]
        K.add(parts, 'yard_log_%d' % k, fam, (v, f), jit=0.004, seed=500 + k)
    # верхнее бревно свалилось на землю перед штабелем
    K.fallen_beam(parts, 'yard_log_fallen', (-0.92, 0.30), (-0.64, 0.52),
                  0.10, seed=503, fam='char', z0=ZD)
    # вязанка соломы выгорела: два пласта на земле, один торчит
    for k, (dy, ang, fam) in enumerate(((0.0, 8.0, 'thatch2'),
                                        (0.12, -12.0, 'char'),
                                        (-0.10, 24.0, 'thatch2'))):
        # Каждому пласту своя высота: два пласта на одном z дают пару
        # совпадающих плоскостей (xray: доля 0.83).
        K.shingle(parts, 'yard_straw_%d' % k, 0.68 + 0.02 * k, -1.20 + dy,
                  0.27, 0.20, ang, 530 + k, fam=fam, z=ZD + 0.012 + 0.012 * k,
                  thick=0.05, tilt=0.01)
    # утоптанная земля перед входом — теперь в пепле, но на своём месте
    K.ash_patch(parts, 'ash_yard', 0.02, 1.26, 0.34, 0.16, 541, z=ZD + 0.006)
    # ГОРЕЛЫЙ ПОЛ: один большой фасет на всю внутренность.  Он и читается как
    # «внутри выгорело», и даёт кадру крупную плоскость (стиль-гейт мерит долю
    # площади в фасетах >=3 %: у руины её легко потерять на мелочи обломков).
    poly = [(-0.70, -1.30), (0.70, -1.30), (0.72, -0.70), (0.68, -0.10),
            (0.72, 0.60), (0.68, 1.30), (-0.68, 1.30), (-0.72, 0.50),
            (-0.68, -0.30), (-0.72, -0.90)]
    v, f = F.prism(poly, ZD + 0.002, ZD + 0.010, axis=2)
    K.add(parts, 'burnt_floor', 'ash', (v, f))
    K.ash_patch(parts, 'ash_inside', -0.15, 0.30, 0.46, 0.40, 542, z=ZD + 0.012)


