"""ruin_house.py — РАЗРУШЕННЫЙ СТАРТОВЫЙ ДОМ (атлас starter_house), пятно 2 x 3.

Целая модель — `art/buildings/starter_house/tools/house.py` (тип `house`,
атлас `mapgen2/assets/starter_house/`).  Руина собрана на ЕГО ЖЕ основании:
`house.build_plinth(parts)` вызывается как есть, поэтому цоколь, лунка,
вынутые валуны, мох и наземный контур — те же, что у целого дома.  Меняются
только стены, кровля и двор: они и должны меняться.

ЧТО СЛОМАНО И ПОЧЕМУ ТАК
------------------------
* Стены — куски с рваной верхней кромкой (`ruinkit.broken_wall`).  На +Y
  (фасад, он же сторона камеры) пролом на всю ширину двери и ещё один у угла;
  на -X (вторая стена к камере) стена выше — по ней руина и узнаётся как дом.
  Края проломов обуглены: после пожара горит то, что осталось.
* Щипец на -Y уцелел наполовину: треугольник от -X до середины.  Он держит
  силуэт двускатной кровли, не притворяясь целой крышей.
* Кровля упала ВНУТРЬ пятна: два куска соломы лежат под наклоном, опираясь на
  остаток стены и на землю, третий — плоский, на обломках.  Стропила — часть
  на стене, часть на земле; ни одно не висит.
* Двор выгорел: штабель брёвен на -X и вязанка соломы на -Y сохранены по
  месту (они входят в `ground` целого дома), но перекрашены в уголь/старую
  солому и раскатаны.  Плюс пепел, угли, щепа и выпавшие камни цоколя.

Пятно 2 x 3: x в -1.0..1.0, y в -1.5..1.5.  Габарит проверяет `canon.py`,
`ground` — упаковщик (`pack_ruins.py`) по модели и сверяет с целым атласом.
"""
import importlib.util
