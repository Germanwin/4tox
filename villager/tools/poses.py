"""poses.py — idle / walk / work. Позы одной модели, а не три модели.

Почему углами, а не отдельными мешами: топология не меняется, значит кадры
анимации не могут разъехаться по форме, а «боб» корпуса получается сам —
ground_lock в person.build сажает фигуру так, чтобы ОПОРНАЯ ступня стояла на
земле. Рисовать покачивание руками не нужно: оно следствие шага.

Три анимации — те же имена и то же число кадров, что у героя
(mapgen2/assets/hero/atlas.json): idle 6 x 8 к/с, walk 8 x 12 к/с, work 8 x 12.
Так новый персонаж встаёт в игру рядом с героем без правок кода.
"""
import math

TAU = 2.0 * math.pi


def _lerp(a, b, t):
    return a + (b - a) * t


def _keys(keys, t):
    """Куски: [(фаза, {углы}), ...] -> углы на фазе t (0..1), линейно."""
    keys = sorted(keys)
    for i in range(len(keys) - 1):
        t0, a = keys[i]
        t1, b = keys[i + 1]
        if t0 <= t <= t1:
            k = 0.0 if t1 == t0 else (t - t0) / (t1 - t0)
            out = dict(a)
            for name, v in b.items():
                out[name] = _lerp(a.get(name, v), v, k)
            for name in a:
                if name not in b:
                    out[name] = a[name]
            return out
    return dict(keys[-1][1])


# ==========================================================================
# IDLE — стоит и дышит. Четыре кадра из шести: два «вдоха» на цикл.
# ==========================================================================
IDLE = [
    (0.00, dict(bob=0.000, chest=0.0, head_pitch=0.0, sh_l=5.0, sh_r=5.0,
                el_l=14.0, el_r=14.0, lean=1.0)),
    (0.25, dict(bob=0.006, chest=1.6, head_pitch=-1.2, sh_l=6.5, sh_r=6.5,
                el_l=15.5, el_r=15.5, lean=0.4)),
    (0.50, dict(bob=0.001, chest=0.4, head_pitch=0.8, sh_l=5.2, sh_r=5.2,
                el_l=14.2, el_r=14.2, lean=1.2)),
    (0.75, dict(bob=0.005, chest=1.2, head_pitch=-0.6, sh_l=6.0, sh_r=6.0,
                el_l=15.0, el_r=15.0, lean=0.6)),
]


def idle(i, n=6):
    p = _keys(IDLE + [(1.0, IDLE[0][1])], (i % n) / float(n))
    # лёгкий поворот головы: «осматривается», но без суеты
    p['head_turn'] = 3.0 * math.sin(TAU * (i % n) / float(n))
    p['head_tilt'] = 1.0 * math.sin(TAU * (i % n) / float(n) + 1.0)
    return p


# ==========================================================================
# WALK — шаг на 8 кадров. Углы аналитические: цикл обязан быть замкнутым, а
# ключи пришлось бы сшивать вручную и на стыке всегда лезет рывок.
# ==========================================================================
# ЧИСЛА ШАГА подобраны замером, а не на глаз: tools/gait_probe.py считает по
# скелету положение ступни ОТНОСИТЕЛЬНО ТАЗА и печатает шаг, опору и клиренс.
WALK_HIP_F = 14.0       # размах бедра ВПЕРЁД, град
WALK_HIP_D = 9.0        # добавка sin^2: сгиб бедра больше разгиба
WALK_KNEE_ST = 6.0      # колено в опоре — чуть согнуто, не «солдатик»
WALK_KNEE_SW = 24.0     # сгиб колена на переносе, град
WALK_KNEE_PH = 225.0    # фаза начала переноса (пик сгиба — на +90°)
WALK_KNEE_PW = 2.0      # сглаживание горба: 1 — узкий, 2 — плавный
WALK_ARM = 15.0         # размах плеча; ОБЕ руки — одинаково


def _hip_walk(t):
    """Бедро качается ВПЕРЁД-НАЗАД относительно таза, вперёд больше.

    Чистая синусоида даёт равный размах в обе стороны, и тогда ступня уезжает
    назад дальше, чем вперёд. У человека сгибание бедра (25..30°) заметно
    больше разгибания (10..15°), поэтому к синусу добавлен sin^2: размах
    смещается вперёд, а функция остаётся гладкой и периодичной — шов цикла
    (кадр 8 -> кадр 0) не рвётся.
    """
    s = math.sin(t)
    return WALK_HIP_F * s + WALK_HIP_D * s * s


def _knee_walk(t):
    """Колено: почти прямое в опоре, сгибается на ПЕРЕНОСЕ (фаза 225..45°).

    Пик сгиба — на 315°, между отрывом (270°) и выносом вперёд (45°): ступня
    поднимается и проходит под тазом СОГНУТОЙ, а не отбрасывается назад. В
    первой версии пик стоял на 218°, то есть ровно тогда, когда бедро шло
    назад, — отсюда и «ноги уходят назад».

    Возведение в степень WALK_KNEE_PW убирает излом max(0, ·): сгиб нарастает
    и спадает плавно, а не скачком в один кадр.
    """
    u = 0.5 * (1.0 + math.sin(t - math.radians(WALK_KNEE_PH)))
    return WALK_KNEE_ST + WALK_KNEE_SW * (u ** WALK_KNEE_PW)


def walk(i, n=8, carry=False):
    """Шаг. carry=True — женская фигура: в левой руке корзина, полный размах
    руки её «уносит» (заказчик видел в этом драку с ведром)."""
    th = TAU * (i % n) / float(n)
    st, ct = math.sin(th), math.cos(th)
    # Ноги в противофазе и по ОДНОЙ кривой со сдвигом на полцикла: так шаг
    # зеркален по построению, и «одна нога шире другой» невозможно.
    hip_l, knee_l = _hip_walk(th), _knee_walk(th)
    hip_r, knee_r = _hip_walk(th + math.pi), _knee_walk(th + math.pi)
    p = dict(
        # bob — смещение таза вверх-вниз. На итоговую фигуру он НЕ влияет:
        # ground_lock сдвигает всё тело целиком и сокращает его до нуля.
        # Настоящий «боб» получается сам — из геометрии опорной ноги.
        bob=-0.010 - 0.008 * math.cos(2.0 * th),
        lean=3.0,
        side=1.6 * st,
        twist=-4.0 * st,
        # Грудь качается ВДВОЕ ЧАЩЕ шага: корпус клюёт на каждом шаге, а не на
        # каждом цикле. Заодно это единственный способ сделать ходьбу честно
        # зеркальной: cos(th) не антисимметричен между половинами цикла, и
        # левая рука с правой качались на 0.7 px по-разному (замер в
        # tools/gait_probe.py), хотя формула у них одна.
        chest=1.0 - 0.8 * math.cos(2.0 * th),
        head_pitch=-1.5,
        head_turn=2.5 * st,
        hip_l=hip_l, knee_l=knee_l, ankle_l=8.0 * math.sin(th + 2.4), out_l=1.8,
        hip_r=hip_r, knee_r=knee_r,
        ankle_r=8.0 * math.sin(th + math.pi + 2.4), out_r=1.8,
        # ОБЕ руки качаются одинаково и в противофазе друг другу: правая рука
        # вперёд, когда вперёд идёт левая нога. Раньше левая качалась на 5°
        # против 15° у правой — это осталось от женской позы «несу корзину»,
        # а у мужчины в руках ничего нет, и качалась ровно одна рука.
        sh_l=-WALK_ARM * st, el_l=16.0 + 6.0 * max(0.0, -st),
        armout_l=10.0, foreout_l=-3.0,
        sh_r=WALK_ARM * st, el_r=16.0 + 6.0 * max(0.0, st),
        armout_r=10.0, foreout_r=-3.0,
        # подол отстаёт от шага: на переносе уезжает назад и в сторону
        skirt_dx=-0.012 * st, skirt_dy=-0.004 * ct,
    )
    if carry:
        p.update(sh_l=-5.0 * st, el_l=26.0 + 4.0 * st)
    return p


