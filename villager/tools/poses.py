def work(i, n=8):
    p = _keys(WORK + [(1.0, WORK[0][1])], (i % n) / float(n))
    # кисть не участвует в ударе: топор посажен в систему кисти (person.build_axe)
    p['hand_r'] = 0.0
    p['hand_l'] = p.get('hand_l', 0.0)
    # подол рубахи отстаёт от корпуса: без этого он «прилипает» к коленям
    p['skirt_dy'] = -0.030 * p['chest'] / 16.0
    p['skirt_dx'] = -0.010 * p['twist'] / 13.0
    return p


ANIMS = {'idle': (idle, 6, 8.0, True), 'walk': (walk, 8, 12.0, True),
         'work': (work, 8, 12.0, False)}


def pose(anim, frame, variant=None):
    """Поза кадра. `variant` нужен ТОЛЬКО ходьбе: у женской фигуры в левой руке
    корзина и размах руки ограничен (см. `walk`). Мужская — обе руки свободны.

    Параметр необязательный: старые вызовы `pose(anim, frame)` дают мужскую
    ходьбу, то есть ровно ту, что уходит в игру.
    """
    fn, n, fps, loop = ANIMS[anim]
    if fn is walk:
        return fn(frame, n, carry=(variant == 'f'))
    return fn(frame, n)
